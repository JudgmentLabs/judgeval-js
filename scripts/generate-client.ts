// Emits from the committed spec:
// - src/internal/api/schema.ts: the spec's types, via openapi-typescript.
// - src/internal/api/operations.ts: one JudgmentApi method per `x-mcp`
//   operation, named after its MCP tool in camelCase.
import openapiTS, { astToString, type SchemaObject } from "openapi-typescript";
import ts from "typescript";
import spec from "../openapi/public-api.json";

// TypeScript rejects a schema type that holds arrays of itself through
// `components["schemas"][name]`, so recursive JSON value schemas use this
// alias instead.
const JSON_VALUE = "JsonValue";

/** Whether `schema`, at `path`, is any JSON value: a primitive, or an array or
 * object of itself. */
function isJsonValue(schema: SchemaObject, path: string | undefined): boolean {
  if (!("anyOf" in schema) || !schema.anyOf || path === undefined) return false;
  const self = (s: unknown) =>
    typeof s === "object" && s !== null && "$ref" in s && s.$ref === path;
  const types = schema.anyOf.map((s) =>
    "type" in s
      ? s.type === "array"
        ? self(s.items) && "array"
        : s.type === "object"
          ? self(s.additionalProperties) && "object"
          : s.type
      : false,
  );
  return (
    types.length === 6 &&
    ["string", "number", "boolean", "null", "array", "object"].every((t) =>
      types.includes(t),
    )
  );
}

const schemaTypes = await openapiTS(
  new URL("../openapi/public-api.json", import.meta.url),
  {
    inject: `export type ${JSON_VALUE} = string | number | boolean | null | ${JSON_VALUE}[] | { [key: string]: ${JSON_VALUE} };`,
    transform: (schema, { path }) =>
      isJsonValue(schema, path)
        ? ts.factory.createTypeReferenceNode(JSON_VALUE)
        : undefined,
  },
);
await Bun.write(
  "src/internal/api/schema.ts",
  `// Generated by scripts/generate-client.ts from openapi/public-api.json. Do not edit.\n${astToString(schemaTypes)}`,
);

type Operation = { summary?: string; "x-mcp"?: { tool: string } };

const methods = Object.entries(
  spec.paths as Record<string, Record<string, Operation>>,
)
  .flatMap(([path, operations]) =>
    Object.entries(operations).map(([method, op]) => ({ path, method, op })),
  )
  .filter(({ op }) => op["x-mcp"])
  .map(({ path, method, op }) => ({
    path,
    method,
    summary: op.summary,
    name: op["x-mcp"]!.tool.replace(/_(\w)/g, (_, c: string) =>
      c.toUpperCase(),
    ),
  }))
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(
    ({ path, method, summary, name }) => `
  /** ${summary ?? name} (\`${method.toUpperCase()} ${path}\`). */
  ${name}(...init: Init<"${path}", "${method}">) {
    return ok(this.client.${method.toUpperCase()}("${path}", ...init));
  }`,
  );

await Bun.write(
  "src/internal/api/operations.ts",
  `// Generated by scripts/generate-client.ts from openapi/public-api.json. Do not edit.
import type { Client, MaybeOptionalInit } from "openapi-fetch";
import { ok } from "./client";
import type { paths } from "./schema";

type Init<P extends keyof paths, M extends keyof paths[P]> =
  undefined extends MaybeOptionalInit<paths[P], M>
    ? [init?: MaybeOptionalInit<paths[P], M>]
    : [init: MaybeOptionalInit<paths[P], M>];

/** One method per public API route, named after the matching MCP tool. */
export class JudgmentApi {
  constructor(private readonly client: Client<paths>) {}
${methods.join("\n")}
}
`,
);
