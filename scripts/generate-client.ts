// Emits src/internal/api/operations.ts: one JudgmentApi method per `x-mcp`
// operation in the committed spec, named after its MCP tool in camelCase.
import spec from "../openapi/public-api.json";

type Operation = {
  summary?: string;
  "x-mcp"?: { tool: string };
  parameters?: { required?: boolean }[];
  requestBody?: { required?: boolean };
};

const methods = Object.entries(
  spec.paths as Record<string, Record<string, Operation>>,
)
  .flatMap(([path, operations]) =>
    Object.entries(operations).map(([method, op]) => ({ path, method, op })),
  )
  .filter(({ op }) => op["x-mcp"])
  .map(({ path, method, op }) => {
    const name = op["x-mcp"]!.tool.replace(/_(\w)/g, (_, c: string) =>
      c.toUpperCase(),
    );
    return {
      path,
      method,
      summary: op.summary,
      name,
      typeName: name[0]!.toUpperCase() + name.slice(1),
      // Mirrors openapi-fetch: init is required when any part of it is.
      initRequired:
        (op.parameters ?? []).some((p) => p.required) ||
        op.requestBody?.required === true,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// Named per-operation types keep signatures readable in editors and the docs.
const types = methods.map(
  ({ path, method, typeName }) => `
export type ${typeName}Options = MaybeOptionalInit<paths["${path}"], "${method}">;
export type ${typeName}Response = Data<"${path}", "${method}">;`,
);

const members = methods.map(
  ({ path, method, summary, name, typeName, initRequired }) => `
  /** ${summary ?? name} (\`${method.toUpperCase()} ${path}\`). */
  ${name}(init${initRequired ? "" : "?"}: ${typeName}Options): Promise<${typeName}Response> {
    return ok(this.client.${method.toUpperCase()}("${path}", init));
  }`,
);

await Bun.write(
  "src/internal/api/operations.ts",
  `// Generated by scripts/generate-client.ts from openapi/public-api.json. Do not edit.
import type { Client, FetchResponse, MaybeOptionalInit } from "openapi-fetch";
import { ok } from "./client";
import type { paths } from "./schema";

/** The 200 JSON body as openapi-fetch returns it (keys typed only \`null\` are dropped). */
type Data<P extends keyof paths, M extends keyof paths[P]> = NonNullable<
  FetchResponse<paths[P][M] & Record<string, unknown>, object, "application/json">["data"]
>;
${types.join("\n")}

/** One method per MCP-tool route in the public API, named after the tool. */
export class JudgmentApi {
  constructor(private readonly client: Client<paths>) {}
${members.join("\n")}
}
`,
);
